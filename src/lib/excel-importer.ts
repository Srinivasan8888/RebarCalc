// BEAM layout
// ---------------------------------------------------------------------------

function parseBeamMetadata(ws: ExcelJS.Worksheet): BBSMetadata {
  const grade = str(ws.getCell('U4')); // "M30 (Fe 550)"
  const concrete = (grade.match(/M\s*(\d+)/)?.[1] ? 'M' + grade.match(/M\s*(\d+)/)![1] : 'M30') as ConcreteGrade;
  const steel = ('Fe' + (grade.match(/Fe\s*(\d+)/)?.[1] ?? '500')) as SteelGrade;
  const developmentLengths: Record<number, number> = {};
  for (let col = 23; col <= 29; col++) { // W..AC
    const dia = num(ws.getCell(3, col));
    if (dia) developmentLengths[dia] = num(ws.getCell(4, col));
  }
  return {
    projectName: str(ws.getCell('B2')).split(':')[1]?.trim() ?? str(ws.getCell('B2')),
    drawingNumber: '',
    itemDescription: str(ws.getCell('B3')),
    concreteGrade: ['M20', 'M25', 'M30', 'M35', 'M40'].includes(concrete) ? concrete : 'M30',
    steelGrade: ['Fe415', 'Fe500', 'Fe550'].includes(steel) ? steel : 'Fe500',
    developmentLengths,
    curtailOffset: num(ws.getCell('R8')) || 300
  };
}

function parseBeamComponents(ws: ExcelJS.Worksheet): ConcreteComponent[] {
  const cover = num(ws.getCell('R4'));
  const components: ConcreteComponent[] = [];
  let group: ConcreteComponent[] = [];
  let sno = 0;

  for (let r = 11; r <= ws.rowCount; r++) {
    const row = ws.getRow(r);
    const name = str(row.getCell('B'));
    if (!name || /^total/i.test(name)) continue;

    // Beam row: width, depth, clear span
    if (num(row.getCell('C')) > 0 && num(row.getCell('D')) > 0 && num(row.getCell('J')) > 0) {
      if (num(row.getCell('A')) > 0) { group = []; sno = num(row.getCell('A')); }
      const beam: ConcreteComponent = {
        id: crypto.randomUUID(),
        name,
        componentType: 'BEAM',
        spanX: num(row.getCell('J')),
        spanY: num(row.getCell('C')),
        depth: num(row.getCell('D')),
        cover,
        beamWidths: { left: num(row.getCell('I')), right: num(row.getCell('K')), top: 0, bottom: 0 },
        bars: []
      };
      group.push(beam);
      components.push(beam);
      if (group.length > 1) group.forEach((b, i) => { b.runId = String(sno); b.runPosition = i + 1; }); // continuous run
      continue;
    }

    // Bar row: needs a diameter and a bar count
    const diameter = num(row.getCell('D'));
    if (!group.length || !diameter || !num(row.getCell('G'))) continue;

    // "B2_Stirrups - Middle" / "B1 & B2-Top Extra …" → that beam; otherwise the group's first beam
    const prefix = name.match(/^([A-Za-z]+\d+[A-Za-z]*)(?:\s*&\s*[A-Za-z]+\d+[A-Za-z]*)?\s*[-_]\s*/);
    const beam = (prefix && group.find(b => b.name.toLowerCase() === prefix[1].toLowerCase())) || group[0];
    const barType = prefix ? name.slice(prefix[0].length) : name;
    const spacing = num(row.getCell('E'));
    group.forEach(b => { b.elementCount = num(row.getCell('F')) || 1; });

    const seg = (col: string) => num(row.getCell(col)) || undefined;
    const bar: ComponentBarEntry = {
      id: crypto.randomUUID(),
      barType,
      direction: 'X',
      diameter,
      spacing,
      barsPerMember: num(row.getCell('G')),
      measurements: { a: num(row.getCell('O')), b: seg('P'), c: seg('Q'), d: seg('R'), e: seg('S'), f: seg('T') },
      manualNoOfDeductions: num(row.getCell('L'))
    };
    const rods = num(row.getCell('H'));
    if (rods !== calculateBarsPerMember(barType, 'X', beam, spacing)) bar.totalMembers = rods;
    beam.bars.push(bar);
  }
  return components;
}

export interface ImportResult { metadata: BBSMetadata; components: ConcreteComponent[]; doubts: string[] }

export async function parseBBSWorkbook(data: ArrayBuffer, existing?: BBSMetadata): Promise<ImportResult> {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(data);
  const sheets = workbook.worksheets;
  if (!sheets.length) throw new Error('Workbook has no sheets');

  if (/description of work/i.test(str(sheets[0].getCell('B10')))) {
    const components = sheets.flatMap(ws => parseBeamComponents(ws));
    if (!components.length) throw new Error('No beams found — expected the "Sample Beam BBS" layout');
    return { metadata: parseBeamMetadata(sheets[0]), components, doubts: [] };
  }

  const schedule = sheets.find(ws => findScheduleHeader(ws));
  if (schedule) return importBeamSchedule(schedule, existing);

  const metadata = parseMetadata(sheets[0]);
  const components = sheets.flatMap(ws => {
    const cover = num(ws.getCell('G4')) || num(sheets[0].getCell('G4'));
    const comps = parseComponents(ws, cover);
    return sheets.length > 1 ? comps.map(c => ({ ...c, description: ws.name })) : comps;
  });
  if (!components.length) throw new Error('No slab components found — expected the "Sample Slab BBS" layout');
  return { metadata, components, doubts: [] };
}
