/**
 * Import a BBS workbook into Component mode. Two layouts are recognised:
 *
 * SLAB ("data/Sample Slab BBS.xlsx"), per sheet = one floor:
 *   A1 "PROJECT :- …"  A2 "Dwg No :- …"  A3 "Item :- …"  B4 concrete grade  D4 steel grade  G4 cover
 *   F2:L2 bar diameters, F3:L3 Ld for those diameters
 *   Component block:  row r   A=S.No  B=name  C=spanX  D=spanY  F=depth  K,L,M,N = top ext L,R,T,B
 *                     row r+2 C=beam left  D=beam top      row r+3 C=beam right  D=beam bottom
 *   Bar rows follow:  B=bar type  E=spacing  F=dia  G=bars/member  H=members  J..P = a..lap  R=bends
 *
 * BEAM SCHEDULE (any sheet whose header row has "Beam", "Bottom" and "Top" headings): rows are
 *   generated by the DRA house rules in schedule-importer.ts and returned with a list of doubts.
 *
 * BEAM BBS ("data/DRA_iHeart_19th_Floor_Beam_BBS.xlsx"), header A10 "S.No" / B10 "Description of work":
 *   B2 "Project Name : …"  B3 item  U4 "M30 (Fe 550)"  R4 cover  R8 curtail offset  W3:AC3 dia / W4:AC4 Ld
 *   Beam row:  A=S.No (first beam of a group only)  B=mark  C=width  D=depth  I=support L  J=clear span  K=support R
 *   Bar row:   B=description  D=dia  E=spacing  F=element count  G=bars  H=rods  L=bends  O..T = legs A..F
 *   "B1_…" / "B1 & B2-…" prefixes name the beam in a continuous group the row belongs to.
 */
import * as ExcelJS from 'exceljs';
import type { BBSMetadata, ConcreteComponent, ComponentBarEntry, ConcreteGrade, SteelGrade } from '../types/component-types';
import { calculateBarsPerMember } from './enhanced-calculator';
import { findScheduleHeader, importBeamSchedule } from './schedule-importer';

type Cell = ExcelJS.Cell;

// Formula cells carry their cached result; take that.
function num(c: Cell): number {
  const v = c.value;
  const r = v && typeof v === 'object' && 'result' in v ? v.result : v;
  return typeof r === 'number' ? r : 0;
}

function str(c: Cell): string {
  const v = c.value;
  if (v == null) return '';
  if (typeof v === 'object') {
    if ('richText' in v) return v.richText.map(t => t.text).join('');
    if ('result' in v) return String(v.result ?? '');
  }
  return String(v).trim();
}

const afterColon = (s: string) => s.split(':-')[1]?.trim() ?? s.trim();

function parseMetadata(ws: ExcelJS.Worksheet): BBSMetadata {
  const concrete = str(ws.getCell('B4')) as ConcreteGrade;
  const steel = ('Fe' + str(ws.getCell('D4')).replace(/\D/g, '')) as SteelGrade;
  const developmentLengths: Record<number, number> = {};
  for (let col = 6; col <= 12; col++) { // F..L
    const dia = num(ws.getCell(2, col));
    if (dia) developmentLengths[dia] = num(ws.getCell(3, col));
  }
  return {
    projectName: afterColon(str(ws.getCell('A1'))),
    drawingNumber: afterColon(str(ws.getCell('A2'))),
    itemDescription: afterColon(str(ws.getCell('A3'))),
    concreteGrade: ['M20', 'M25', 'M30', 'M35', 'M40'].includes(concrete) ? concrete : 'M30',
    steelGrade: ['Fe415', 'Fe500', 'Fe550'].includes(steel) ? steel : 'Fe500',
    developmentLengths
  };
}

function parseComponents(ws: ExcelJS.Worksheet, cover: number): ConcreteComponent[] {
  const components: ConcreteComponent[] = [];
  let current: ConcreteComponent | undefined;

  for (let r = 5; r <= ws.rowCount; r++) {
    const row = ws.getRow(r);
    const name = str(row.getCell('B'));
    if (!name || /^total/i.test(name)) continue;

    // Component header: S.No, name, spans
    if (num(row.getCell('A')) > 0 && num(row.getCell('C')) > 0 && num(row.getCell('D')) > 0) {
      current = {
        id: crypto.randomUUID(),
        name,
        componentType: 'SLAB',
        spanX: num(row.getCell('C')),
        spanY: num(row.getCell('D')),
        depth: num(row.getCell('F')),
        cover,
        beamWidths: {
          left: num(ws.getRow(r + 2).getCell('C')), right: num(ws.getRow(r + 3).getCell('C')),
          top: num(ws.getRow(r + 2).getCell('D')), bottom: num(ws.getRow(r + 3).getCell('D'))
        },
        topExtensions: {
          left: num(row.getCell('K')), right: num(row.getCell('L')),
          top: num(row.getCell('M')), bottom: num(row.getCell('N'))
        },
        bars: []
      };
      components.push(current);
      r += 3;
      continue;
    }

    // Bar row: needs a spacing and a diameter
    const spacing = num(row.getCell('E'));
    const diameter = num(row.getCell('F'));
    if (!current || !spacing || !diameter) continue;

    const direction = /\(Y\s*-\s*Y\)/i.test(name) ? 'Y' : 'X';
    const seg = (col: string) => num(row.getCell(col)) || undefined;
    const bar: ComponentBarEntry = {
      id: crypto.randomUUID(),
      barType: name,
      direction,
      diameter,
      spacing,
      barsPerMember: num(row.getCell('G')) || 1,
      measurements: { a: num(row.getCell('J')), b: seg('K'), c: seg('L'), d: seg('M'), e: seg('N'), f: seg('O'), lap: seg('P') },
      manualNoOfDeductions: seg('R')
    };
    // Keep the sheet's member count only where our formula would differ, so edits still recompute
    const members = num(row.getCell('H'));
    if (members && members !== calculateBarsPerMember(name, direction, current, spacing)) bar.totalMembers = members;
    current.bars.push(bar);
  }
  return components;
}

